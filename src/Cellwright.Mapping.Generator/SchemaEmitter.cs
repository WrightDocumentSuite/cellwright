using System.Text;

namespace Cellwright.Mapping.Generator;

/// <summary>
/// Emits the partial type implementing <c>IRowSchema&lt;T&gt;</c> for one <see cref="RowModel"/>.
/// All type references are fully qualified; helper members carry the <c>__cw</c> prefix
/// to stay clear of user code.
/// </summary>
internal static class SchemaEmitter
{
    public static string Emit(RowModel model)
    {
        var sb = new StringBuilder(4096);
        sb.AppendLine("// <auto-generated by Cellwright.Mapping.Generator/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        if (model.Namespace is not null)
        {
            sb.Append("namespace ").Append(model.Namespace).AppendLine(";");
            sb.AppendLine();
        }

        string self = model.TypeName;
        string schema = $"global::Cellwright.Mapping.IRowSchema<{self}>";

        sb.Append("partial ").Append(model.TypeKeyword).Append(' ').Append(self)
            .Append(" : ").AppendLine(schema);
        sb.AppendLine("{");

        EmitHeaders(sb, model);
        sb.AppendLine();
        sb.Append("    static int ").Append(schema).Append(".ColumnCount => ").Append(model.Columns.Length).AppendLine(";");
        sb.AppendLine();
        sb.Append("    static bool ").Append(schema).Append(".HasHeader => ")
            .Append(model.HasHeader ? "true" : "false").AppendLine(";");
        sb.AppendLine();
        sb.Append("    static global::System.ReadOnlySpan<string> ").Append(schema).AppendLine(".Headers => __cwHeaders;");
        sb.AppendLine();
        EmitRead(sb, model, self, schema);
        sb.AppendLine();
        EmitWrite(sb, model, self, schema);
        sb.AppendLine();
        EmitRegisterStyles(sb, model, schema);
        sb.AppendLine();
        EmitCellHelper(sb);
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void EmitHeaders(StringBuilder sb, RowModel model)
    {
        sb.Append("    private static readonly string[] __cwHeaders = [");
        for (int i = 0; i < model.Columns.Length; i++)
        {
            if (i > 0)
                sb.Append(", ");
            sb.Append(Quote(model.Columns[i].Header));
        }

        sb.AppendLine("];");
    }

    private static void EmitRead(StringBuilder sb, RowModel model, string self, string schema)
    {
        sb.Append("    static ").Append(self).Append(' ').Append(schema)
            .AppendLine(".Read(scoped global::System.ReadOnlySpan<global::Cellwright.CellValue> cells, scoped global::System.ReadOnlySpan<int> columnMap)");

        if (model.UseConstructor)
        {
            sb.Append("        => new ").Append(self).AppendLine("(");
            for (int i = 0; i < model.Columns.Length; i++)
            {
                sb.Append("            ").Append(Conversion(model.Columns[i], i));
                sb.AppendLine(i < model.Columns.Length - 1 ? "," : ");");
            }
        }
        else
        {
            sb.Append("        => new ").Append(self).AppendLine("()");
            sb.AppendLine("        {");
            for (int i = 0; i < model.Columns.Length; i++)
            {
                sb.Append("            ").Append(model.Columns[i].PropertyName).Append(" = ")
                    .Append(Conversion(model.Columns[i], i)).AppendLine(",");
            }

            sb.AppendLine("        };");
        }
    }

    private static void EmitWrite(StringBuilder sb, RowModel model, string self, string schema)
    {
        sb.Append("    static void ").Append(schema).Append(".Write(").Append(self)
            .AppendLine(" row, scoped global::System.Span<global::Cellwright.CellValue> cells)");
        sb.AppendLine("    {");
        for (int i = 0; i < model.Columns.Length; i++)
        {
            sb.Append("        cells[").Append(i).Append("] = row.")
                .Append(model.Columns[i].PropertyName).AppendLine(";");
        }

        sb.AppendLine("    }");
    }

    private static void EmitRegisterStyles(StringBuilder sb, RowModel model, string schema)
    {
        sb.Append("    static void ").Append(schema)
            .AppendLine(".RegisterStyles(global::System.Func<global::Cellwright.CellStyle, global::Cellwright.StyleId> registerStyle, scoped global::System.Span<global::Cellwright.StyleId> styles)");
        sb.AppendLine("    {");
        for (int i = 0; i < model.Columns.Length; i++)
        {
            if (model.Columns[i].Format is not { } format)
                continue;
            sb.Append("        styles[").Append(i)
                .Append("] = registerStyle(new global::Cellwright.CellStyle { NumberFormat = ")
                .Append(Quote(format)).AppendLine(" });");
        }

        sb.AppendLine("    }");
    }

    private static void EmitCellHelper(StringBuilder sb)
    {
        sb.AppendLine("    private static global::Cellwright.CellValue __cwCell(scoped global::System.ReadOnlySpan<global::Cellwright.CellValue> cells, scoped global::System.ReadOnlySpan<int> columnMap, int index)");
        sb.AppendLine("    {");
        sb.AppendLine("        int column = columnMap[index];");
        sb.AppendLine("        return (uint)column < (uint)cells.Length ? cells[column] : default;");
        sb.AppendLine("    }");
    }

    private static string Conversion(ColumnModel column, int index)
    {
        string method = column.Kind switch
        {
            ColumnKind.Text => column.IsNullable ? "ToTextOrNull" : "ToText",
            ColumnKind.Double => column.IsNullable ? "ToDoubleOrNull" : "ToDouble",
            ColumnKind.Int32 => column.IsNullable ? "ToInt32OrNull" : "ToInt32",
            ColumnKind.Int64 => column.IsNullable ? "ToInt64OrNull" : "ToInt64",
            ColumnKind.Decimal => column.IsNullable ? "ToDecimalOrNull" : "ToDecimal",
            ColumnKind.Boolean => column.IsNullable ? "ToBooleanOrNull" : "ToBoolean",
            ColumnKind.DateTime => column.IsNullable ? "ToDateTimeOrNull" : "ToDateTime",
            ColumnKind.DateOnly => column.IsNullable ? "ToDateOnlyOrNull" : "ToDateOnly",
            ColumnKind.TimeSpan => column.IsNullable ? "ToTimeSpanOrNull" : "ToTimeSpan",
            _ => "ToCellValue",
        };

        return $"global::Cellwright.Mapping.RowConvert.{method}(__cwCell(cells, columnMap, {index}), {Quote(column.Header)})";
    }

    private static string Quote(string text) =>
        "\"" + text.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
}
